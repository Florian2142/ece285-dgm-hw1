"""Put one run's figures and numbers into the HW1 report (homeworks/hw1/report/generated/).

    uv run python -m hw1.report_assets                 # latest run
    uv run python -m hw1.report_assets --run <name>    # a specific run
    uv run python -m hw1.report_assets --placeholder   # reset to placeholders (no run needed)

Writes loss_curves.pdf, samples.png, reconstructions.png, hparams.tex, results.tex, and
source.txt. The report \\input's these files, so rebuilding the PDF shows the chosen run.
Run ``python -m hw1.evaluate`` first; without its scores the numbers stay "??".
"""

from __future__ import annotations

import argparse
import math
import shutil
from datetime import date
from pathlib import Path

from dgm.data.chest_xray import processed_dir
from dgm.training.loggers import read_csv
from dgm.training.runs import read_json, resolve_run_dir
from dgm.utils.config import load_config
from dgm.utils.viz import plot_training_curves
from hw1.config import Config
from hw1.train import DEFAULT_CONFIG, EXPERIMENT

GENERATED = Path(__file__).parent / "report" / "generated"
PLACEHOLDER = r"\textcolor{red}{??}"
# Score macros: <row><score>. Rows: samples (mean +- std over repeats), reconstructions,
# real training images (floor). Scores: FID (tutorial/ignite default), FIDpool (2048-d), IS.
SCORE_MACROS = {
    "fid": "FID",
    "fid_2048": "FIDpool",
    "inception_score": "IS",
}
ROWS = {"samples": "", "reconstructions": "recon", "real_train_images": "real"}
MACROS = (
    *(f"Result{score}{row}" for row in ROWS.values() for score in SCORE_MACROS.values()),
    "ResultNumSamples",
    "ResultRepeats",
    "ResultBestEpoch",
    "ResultValNegELBO",
    "ResultParams",
    "ResultTrainTime",
    "ResultTrainImages",
    "ResultValImages",
    "ResultTestImages",
)


def latex_number(x: float) -> str:
    """1e-3 -> 10^{-3}, 3e-4 -> 3\\times10^{-4}, 0.5 -> 0.5 (for use in math mode)."""
    if x == 0:
        return "0"
    exponent = math.floor(math.log10(abs(x)))
    mantissa = x / 10**exponent
    if -2 <= exponent <= 3:
        return f"{x:g}"
    if math.isclose(mantissa, 1.0):
        return f"10^{{{exponent}}}"
    return f"{mantissa:g}\\times10^{{{exponent}}}"


def decimals(value: float) -> int:
    """Digits that suit both scales: tutorial FID (< 1) and FID-2048 (tens to hundreds)."""
    return 4 if abs(value) < 1 else 2 if abs(value) < 100 else 1


def number(value: float) -> str:
    return f"{value:.{decimals(value)}f}"


def pm(summary: dict) -> str:
    """``mean \\pm std`` with the decimals of the mean for both numbers."""
    d = decimals(summary["mean"])
    return f"\\ensuremath{{{summary['mean']:.{d}f} \\pm {summary['std']:.{d}f}}}"


def hparams_tex(cfg: Config, params: int | None, best_epoch: int | None) -> str:
    m, t, d = cfg.model, cfg.train, cfg.data
    likelihood = (
        "Bernoulli" if m.likelihood == "bernoulli" else f"Gaussian, $\\sigma={m.gaussian_sigma:g}$"
    )
    optimizer = f"Adam, learning rate ${latex_number(t.lr)}$"
    if t.weight_decay:
        optimizer += f", weight decay ${latex_number(t.weight_decay)}$"
    beta = f"{t.beta:g}" + (f", warm-up {t.kl_warmup_epochs} epochs" if t.kl_warmup_epochs else "")
    rows = [
        ("Image size", f"${d.image_size}\\times{d.image_size}$, gray, $[0,1]$"),
        ("Latent dimension $K$", str(m.latent_dim)),
        ("Hidden channels", str(m.hidden_channels)),
        ("Likelihood $p_\\theta(\\vx\\mid\\vz)$", likelihood),
        ("Optimizer", optimizer),
        ("Batch size", str(d.batch_size)),
        ("Epochs (best)", f"{t.epochs} ({best_epoch if best_epoch else PLACEHOLDER})"),
        ("KL weight $\\beta$", beta),
        ("Gradient clipping", f"norm {t.grad_clip_norm:g}" if t.grad_clip_norm else "none"),
        ("Parameters", f"{params / 1e6:.2f}\\,M" if params else PLACEHOLDER),
        ("Seed", str(t.seed)),
    ]
    # Two name/value pairs per line keep the table short (2-page report).
    half = (len(rows) + 1) // 2
    left, right = rows[:half], rows[half:] + [("", "")] * (2 * half - len(rows))
    lines = [
        "% Generated by `python -m hw1.report_assets`. Do not edit by hand.",
        "\\begin{tabular}{@{}ll@{\\hspace{2em}}ll@{}}",
        "\\toprule",
        *(f"{a} & {b} & {c} & {e} \\\\" for (a, b), (c, e) in zip(left, right, strict=True)),
        "\\bottomrule",
        "\\end{tabular}",
    ]
    return "\n".join(lines) + "\n"


def results_tex(values: dict[str, str], source: str) -> str:
    lines = [
        "% Generated by `python -m hw1.report_assets`. Do not edit by hand.",
        f"% Source: {source}",
    ]
    lines += [f"\\newcommand{{\\{name}}}{{{values.get(name, PLACEHOLDER)}}}" for name in MACROS]
    return "\n".join(lines) + "\n"


def dataset_counts(image_size: int) -> dict[str, str]:
    meta_path = processed_dir(image_size) / "meta.json"
    if not meta_path.exists():
        return {}
    counts = read_json(meta_path)["counts"]
    return {
        "ResultTrainImages": f"{counts['train']['total']:,}",
        "ResultValImages": f"{counts['val']['total']:,}",
        "ResultTestImages": f"{counts['test']['total']:,}",
    }


def write_placeholders() -> None:
    GENERATED.mkdir(parents=True, exist_ok=True)
    for name in ("loss_curves.pdf", "loss_curves.png", "samples.png", "reconstructions.png"):
        (GENERATED / name).unlink(missing_ok=True)
    cfg = load_config(Config, DEFAULT_CONFIG)
    (GENERATED / "hparams.tex").write_text(
        hparams_tex(cfg, None, None), encoding="utf-8", newline="\n"
    )
    (GENERATED / "results.tex").write_text(
        results_tex(dataset_counts(cfg.data.image_size), "placeholders (no run selected yet)"),
        encoding="utf-8",
        newline="\n",
    )
    (GENERATED / "source.txt").write_text(
        "placeholders: no run selected yet\n", encoding="utf-8", newline="\n"
    )
    print(f"reset {GENERATED} to placeholders")


def export(run_dir: Path) -> None:
    GENERATED.mkdir(parents=True, exist_ok=True)
    cfg = load_config(Config, run_dir / "config.yaml")
    env = read_json(run_dir / "env.json") if (run_dir / "env.json").exists() else {}
    summary = read_json(run_dir / "summary.json") if (run_dir / "summary.json").exists() else {}
    metrics_path = run_dir / "eval" / "metrics.json"
    scores = read_json(metrics_path) if metrics_path.exists() else {}

    plot_training_curves(read_csv(run_dir / "metrics.csv"), GENERATED / "loss_curves")
    for name in ("samples.png", "reconstructions.png"):
        src = run_dir / "eval" / name
        if src.exists():
            shutil.copy2(src, GENERATED / name)
        else:
            (GENERATED / name).unlink(missing_ok=True)

    values = dataset_counts(cfg.data.image_size)
    if summary:
        values["ResultBestEpoch"] = str(summary["best_epoch"])
        values["ResultValNegELBO"] = f"{summary['best_val_neg_elbo']:.1f}"
        values["ResultTrainTime"] = f"{summary['train_time_s'] / 60:.0f}\\,min"
    if env.get("parameters"):
        values["ResultParams"] = f"{env['parameters'] / 1e6:.2f}\\,M"
    if "samples" in scores:
        values["ResultNumSamples"] = f"{scores['num_samples']:,}"
        values["ResultRepeats"] = str(scores["repeats"])
        for row_key, row in ROWS.items():
            for score_key, score in SCORE_MACROS.items():
                if row_key == "samples":
                    values[f"Result{score}"] = pm(scores["samples"][score_key])
                elif row_key in scores:
                    values[f"Result{score}{row}"] = number(scores[row_key][score_key])

    source = (
        f"{run_dir.name} (git {env.get('git') or 'unknown'}), exported {date.today().isoformat()}"
    )
    best_epoch = summary.get("best_epoch")
    (GENERATED / "hparams.tex").write_text(
        hparams_tex(cfg, env.get("parameters"), best_epoch), encoding="utf-8", newline="\n"
    )
    (GENERATED / "results.tex").write_text(
        results_tex(values, source), encoding="utf-8", newline="\n"
    )
    (GENERATED / "source.txt").write_text(source + "\n", encoding="utf-8", newline="\n")
    missing = [name for name in MACROS if name not in values]
    print(f"exported {run_dir.name} -> {GENERATED}")
    if missing:
        print(
            f"still placeholders: {', '.join(missing)}"
            + ("" if scores else "  (run: uv run python -m hw1.evaluate)")
        )


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--run", default="latest", help="run name or folder under runs/hw1 (default: latest)"
    )
    parser.add_argument(
        "--placeholder", action="store_true", help="reset the report to placeholders"
    )
    args = parser.parse_args(argv)
    if args.placeholder:
        write_placeholders()
        return
    try:
        export(resolve_run_dir(EXPERIMENT, args.run))
    except FileNotFoundError as err:
        raise SystemExit(f"error: {err}") from None


if __name__ == "__main__":
    main()
